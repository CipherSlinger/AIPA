const SUPPORTED_LANGS = Object.freeze(["en", "zh", "ko"]);

function createTranslator(getLang) {
  if (typeof getLang !== "function") {
    throw new TypeError("createTranslator(getLang): getLang must be a function");
  }
  return function t(key) {
    const lang = getLang();
    const dict = i18n[lang] || i18n.en;
    return dict[key] || key;
  };
}

// The main process requires this file; the pet's notice log loads it as a
// plain script (it has no Node integration) so both surfaces share one table.
if (typeof module !== "undefined" && module.exports) {
  module.exports = {
    i18n,
    SUPPORTED_LANGS,
    createTranslator,
  };
}
if (typeof window !== "undefined") {
  window.clawdI18n = { i18n, SUPPORTED_LANGS, createTranslator };
}
