/**
 * Chaining one job to another: what a chain may name, what must be refused,
 * and whether a finished run starts its successor.
 *
 * A chain is an explicit instruction — "when this one succeeds, start that one"
 * — and it is the only way a job can start another. That makes two things worth
 * keeping in one pure module rather than spread through the scheduler:
 *
 *  - a loop is refused when the user saves, naming the job that would close it,
 *    because a self-feeding chain is a runaway nobody asked for and the ticker
 *    would keep it going all night;
 *  - a successor is started by the run that just finished, never by a timer, so
 *    "did it start?" can be answered at the only moment the answer exists.
 *
 * Electron-free (types and arithmetic only) so the harness can exercise every
 * rule without a store, a window or a clock.
 */
import type { AutomationChainNote, AutomationJob, AutomationJobChain } from './types'

/**
 * How many chained jobs one sequence may enter, successor by successor.
 *
 * Four is a deliberate bound, not a tuning knob: a chain is a hand-written
 * shortcut between jobs the user made, and a sequence longer the user can count
 * on one hand is almost certainly a loop that slipped past save time. Hitting
 * the cap never silently drops the edge — the run that could not go deeper
 * records a note, so the history says the chain stopped rather than pretending
 * it ended.
 */
export const CHAIN_MAX_DEPTH = 4

/**
 * Longest target id a chain may store.
 *
 * Ids are generated by the scheduler and short; this only stops a hand-edited
 * or corrupt value from becoming a whole paragraph in `automations.json`.
 */
export const MAX_CHAIN_TARGET_CHARS = 128

/** The notes a run's chain record may carry, in the order they are explained. */
export const CHAIN_NOTES: readonly AutomationChainNote[] = [
  'target_missing',
  'target_disabled',
  'target_busy',
  'paused',
  'depth_limit',
  'target_refused',
]

export function isChainNote(value: unknown): value is AutomationChainNote {
  return typeof value === 'string' && (CHAIN_NOTES as readonly string[]).includes(value)
}

function cleanTarget(value: unknown, ownId: string | undefined): string | undefined {
  if (typeof value !== 'string') return undefined
  const id = value.trim()
  if (!id || id.length > MAX_CHAIN_TARGET_CHARS) return undefined
  // A job that names itself is a loop of length one. The store drops the edge
  // when reading a file (a hand edit, never a save — `checkJobChainInput`
  // refuses that with a named error), so this only repairs corrupt state.
  if (ownId !== undefined && id === ownId) return undefined
  return id
}

/**
 * A chain as it may be restored from disk, or absent.
 *
 * Each side is validated on its own: a malformed `onFailure` drops only that
 * side, and a chain with nothing left disappears rather than being stored as an
 * empty object. A target id that no longer matches a live job is deliberately
 * kept — the user may restore that job from Recently deleted, and only the user
 * may disconnect the edge.
 */
export function normalizeJobChain(raw: unknown, ownId?: string): AutomationJobChain | undefined {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return undefined
  const chain = raw as Record<string, unknown>
  const onSuccess = cleanTarget(chain.onSuccess, ownId)
  const onFailure = cleanTarget(chain.onFailure, ownId)
  if (!onSuccess && !onFailure) return undefined
  return {
    ...(onSuccess ? { onSuccess } : {}),
    ...(onFailure ? { onFailure } : {}),
  }
}

export interface ChainCycleHit {
  /** The job whose edge points back at the job being saved. */
  jobId: string
  /** Its name at save time, so the refusal can say which job closes the loop. */
  jobName: string
}

/**
 * The job that would close a loop if `chain` were saved on `sourceId`.
 *
 * The walk follows both of a job's edges — a chain that loops through an
 * `onFailure` side is just as able to run forever as one that loops through
 * `onSuccess`. The edited job's edges are the draft being saved, not the stored
 * ones; every other job's are what the store holds.
 *
 * `null` means no loop. A chain that merely converges — two jobs both leading to
 * the same third job — is not a loop and is accepted: the depth cap bounds the
 * sequence, and refusing convergence would make the feature unusable.
 */
export function findChainCycle(
  jobs: readonly AutomationJob[],
  sourceId: string,
  chain: AutomationJobChain,
): ChainCycleHit | null {
  const byId = new Map<string, AutomationJob>()
  for (const job of jobs) byId.set(job.id, job)

  const edgesFor = (id: string): string[] => {
    const stored = id === sourceId ? chain : byId.get(id)?.chain
    if (!stored) return []
    return [stored.onSuccess, stored.onFailure]
      .filter((target): target is string => typeof target === 'string' && target.length > 0)
  }

  const queue: Array<{ id: string; from: string }> = edgesFor(sourceId)
    .map(id => ({ id, from: sourceId }))
  const seen = new Set<string>()
  while (queue.length > 0) {
    const { id, from } = queue.shift() as { id: string; from: string }
    if (id === sourceId) {
      const closer = byId.get(from)
      return { jobId: from, jobName: closer?.name ?? from }
    }
    // A loop that was already in the file (it can only come from a hand edit or
    // an older build) must not make this walk spin forever. It is not this
    // save's problem to report; the save itself is judged on its own edges.
    if (seen.has(id)) continue
    seen.add(id)
    for (const next of edgesFor(id)) queue.push({ id: next, from: id })
  }
  return null
}

export interface ChainValidationError {
  code: 'chain_invalid' | 'chain_cycle'
  /** A name the message needs; set for `chain_cycle`, absent otherwise. */
  detail?: string
}

export type ChainValidation =
  | { ok: true; chain?: AutomationJobChain }
  | { ok: false; error: ChainValidationError }

function checkTarget(
  value: unknown,
  own: { id?: string; name: string },
): { ok: true; id?: string } | { ok: false; error: ChainValidationError } {
  if (value === undefined || value === null || value === '') return { ok: true }
  if (typeof value !== 'string') return { ok: false, error: { code: 'chain_invalid' } }
  const id = value.trim()
  if (!id) return { ok: true }
  if (id.length > MAX_CHAIN_TARGET_CHARS) return { ok: false, error: { code: 'chain_invalid' } }
  // Self-reference is a loop of length one and is refused in the same shape as
  // any other loop, naming the job. Dropping it silently would leave the user
  // believing the chain was saved.
  if (own.id !== undefined && id === own.id) {
    return { ok: false, error: { code: 'chain_cycle', detail: own.name } }
  }
  return { ok: true, id }
}

/**
 * A chain as the user just submitted it.
 *
 * Unlike `normalizeJobChain` this refuses rather than drops: a save is a
 * deliberate act, so an unusable target or a loop must come back as an error the
 * user can read, never be quietly removed. `own` carries the job's id and name —
 * the id is absent on create (nothing can point at a job that does not exist
 * yet), and the name is what a loop refusal names.
 */
export function checkJobChainInput(
  value: unknown,
  own: { id?: string; name: string },
  jobs: readonly AutomationJob[],
): ChainValidation {
  if (value === undefined || value === null) return { ok: true }
  if (typeof value !== 'object' || Array.isArray(value)) {
    return { ok: false, error: { code: 'chain_invalid' } }
  }
  const raw = value as Record<string, unknown>
  const onSuccess = checkTarget(raw.onSuccess, own)
  if (!onSuccess.ok) return onSuccess
  const onFailure = checkTarget(raw.onFailure, own)
  if (!onFailure.ok) return onFailure

  const chain = normalizeJobChain(
    { onSuccess: onSuccess.id, onFailure: onFailure.id },
    own.id,
  )
  if (!chain) return { ok: true }
  if (own.id !== undefined) {
    const cycle = findChainCycle(jobs, own.id, chain)
    if (cycle) {
      return { ok: false, error: { code: 'chain_cycle', detail: cycle.jobName } }
    }
  }
  return { ok: true, chain }
}

/**
 * What a finished run decided about the job its chain named.
 *
 * `none` covers every ordinary run — no chain, a skipped run, a failure whose
 * retry is still waiting — and writes nothing to the record. The other two are
 * always recorded: the history must be able to say either which job followed or
 * why none did.
 */
export type ChainPlan =
  | { kind: 'none' }
  | { kind: 'note'; note: AutomationChainNote }
  | { kind: 'start'; targetId: string; targetName: string; depth: number }

export interface ChainPlanInput {
  chain: AutomationJobChain | undefined
  /**
   * How the run ended. `'skipped'` never chains: nothing ran, so there is no
   * outcome to follow, and the rails that refuse runs must not become a way to
   * start work.
   */
  status: 'success' | 'error' | 'skipped'
  /**
   * A failed attempt with a retry still pending has not finished the occurrence.
   * The chain waits for the attempt that settles it, so a retry that finally
   * works fires `onSuccess` and never also `onFailure`.
   */
  retryPending: boolean
  /** 0 for a run nothing chained into; the successor would be one deeper. */
  depth: number
  jobs: readonly AutomationJob[]
  running: ReadonlySet<string>
  pausedAll: boolean
  maxConcurrentRuns: number
  /** The target still has hourly capacity. Injected so this module stays pure. */
  hasHourlyCapacity: (job: AutomationJob) => boolean
}

/**
 * Decide, synchronously, whether the run that just finished starts a successor.
 *
 * Every check here is a question the scheduler would otherwise ask on the next
 * tick — a chained start is a start, so it meets the same rails as a clock tick.
 * Doing them in one place is what lets the source job's record name the successor
 * only when a run really began, and say why when none did.
 *
 * A job the user switched off is refused rather than started (`target_disabled`):
 * the switch is the user's current instruction, and a chain must not quietly
 * override it. The dialog says so before the chain is saved.
 */
export function planChain(input: ChainPlanInput): ChainPlan {
  const { chain, status } = input
  if (status === 'skipped' || !chain) return { kind: 'none' }
  const targetId = status === 'success' ? chain.onSuccess : chain.onFailure
  if (!targetId) return { kind: 'none' }
  if (status === 'error' && input.retryPending) return { kind: 'none' }

  // Depth first: a successor beyond the cap must not be judged by rails, because
  // no target is going to run however healthy it is.
  const depth = input.depth + 1
  if (depth > CHAIN_MAX_DEPTH) return { kind: 'note', note: 'depth_limit' }

  const target = input.jobs.find(job => job.id === targetId)
  if (!target) return { kind: 'note', note: 'target_missing' }
  // The global pause suspends unattended starts; a chain is unattended, and the
  // run that finished may have been started before the user pressed pause.
  if (input.pausedAll) return { kind: 'note', note: 'paused' }
  if (target.enabled !== true) return { kind: 'note', note: 'target_disabled' }
  // A chained start never queues: holding it would run it minutes later, after
  // the thing it was meant to follow, and the source job would already be over.
  if (input.running.has(target.id) || input.running.size >= input.maxConcurrentRuns) {
    return { kind: 'note', note: 'target_busy' }
  }
  // The runaway guard is a start decision, not a run decision: a chain must not
  // be the door around it.
  if (!input.hasHourlyCapacity(target)) return { kind: 'note', note: 'target_busy' }
  return { kind: 'start', targetId: target.id, targetName: target.name, depth }
}
